CREATE TABLE IF NOT EXISTS contents (
 id TEXT PRIMARY KEY,
 event_id TEXT UNIQUE REFERENCES audit.events(id) ON DELETE CASCADE,
 visit_id TEXT NOT NULL REFERENCES audit.visits(id) ON DELETE CASCADE,
 url TEXT NOT NULL, payload JSONB NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS subscribers (
 id TEXT PRIMARY KEY, name TEXT NOT NULL UNIQUE CHECK (length(trim(name))>0),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS subscriber_contents (
 subscriber_id TEXT NOT NULL REFERENCES subscribers(id) ON DELETE CASCADE,
 content_id TEXT NOT NULL REFERENCES contents(id) ON DELETE CASCADE,
 delivered BOOLEAN NOT NULL DEFAULT false,
 delivered_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 PRIMARY KEY(subscriber_id,content_id),
 CHECK ((delivered AND delivered_at IS NOT NULL) OR (NOT delivered AND delivered_at IS NULL))
);
CREATE INDEX IF NOT EXISTS pending_subscriber_contents ON subscriber_contents(subscriber_id,created_at,content_id) WHERE NOT delivered;
-- Serialize both kinds of INSERT before their triggers read the opposite table.
-- READ COMMITTED trigger queries see the transaction that released this lock.
CREATE OR REPLACE FUNCTION lock_subscription_creation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 PERFORM pg_advisory_xact_lock(73492002);
 RETURN NULL;
END $$;
CREATE OR REPLACE FUNCTION subscribe_existing_contents() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 INSERT INTO public.subscriber_contents(subscriber_id,content_id)
 SELECT NEW.id,id FROM public.contents ON CONFLICT DO NOTHING;
 RETURN NEW;
END $$;
CREATE OR REPLACE FUNCTION publish_content() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 INSERT INTO public.subscriber_contents(subscriber_id,content_id)
 SELECT id,NEW.id FROM public.subscribers ON CONFLICT DO NOTHING;
 RETURN NEW;
END $$;
CREATE OR REPLACE FUNCTION capture_content_event() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 INSERT INTO public.contents(id,event_id,visit_id,url,payload,created_at)
 SELECT NEW.id,NEW.id,NEW.visit_id,coalesce(v.final_uri,v.canonical_uri),NEW.payload_json::jsonb,NEW.created_at::timestamptz
 FROM audit.visits v WHERE v.id=NEW.visit_id ON CONFLICT DO NOTHING;
 RETURN NEW;
END $$;
CREATE OR REPLACE TRIGGER subscribers_lock BEFORE INSERT ON subscribers FOR EACH STATEMENT EXECUTE FUNCTION lock_subscription_creation();
CREATE OR REPLACE TRIGGER contents_lock BEFORE INSERT ON contents FOR EACH STATEMENT EXECUTE FUNCTION lock_subscription_creation();
CREATE OR REPLACE TRIGGER subscribers_backfill AFTER INSERT ON subscribers FOR EACH ROW EXECUTE FUNCTION subscribe_existing_contents();
CREATE OR REPLACE TRIGGER contents_fanout AFTER INSERT ON contents FOR EACH ROW EXECUTE FUNCTION publish_content();
CREATE OR REPLACE TRIGGER events_publish AFTER INSERT ON audit.events FOR EACH ROW EXECUTE FUNCTION capture_content_event();

